def build() -> list[dict]:
    items: list[dict] = []

    def add(texts, skill, tags=()):
        for t in texts:
            items.append({"question": t, "skill": skill, "tags": list(tags)})

    # nl2sql：把主语/时间/指标做叉乘，扩大数量并保持语义同一
    subjects = ["华东区", "各门店", "所有门店", "华南区", "各区域", "全公司", "北京", "每个城市", "Top门店", "每个大区"]
    times = ["上月", "近7天", "本月", "今年", "2025年", "上一季度", "第二季度", "近30天", "近90天"]
    metrics = ["销售额", "GMV", "订单量", "退货率", "客单价", "毛利额", "库存量", "销售收入", "退款金额", "净利润"]
    tpls = ["{s}{t}的{m}", "{s}{t}的{m}是多少", "{s}{m}排名", "{s}{t}{m}汇总"]
    for (s, t, m, tp) in itertools.islice(itertools.product(subjects, times, ["销售额", "GMV", "订单量"], ["{s}{t}的{m}是多少", "{s}{m}排名"]), 0, 60):
        add([tp.format(s=s, t=t, m=m)], "nl2sql", tags=("tpl",))

    add(NL2SQL_T, "nl2sql", tags=("curated",))
    # 指标类
    for m in ["销售额", "GMV", "营业收入", "退货率", "客单价", "毛利率", "净利润", "库存"]:
        add([f"帮我统计一下每个大区的{m}", f"2025年各区域的{m}对比"], "nl2sql", tags=("metric",))

    add(RAG_Q, "rag", tags=("curated",))
    add([f"{q}，请根据政策文件回答" for q in RAG_Q[:10]], "rag", tags=("policy",))
    rag_faq = [
        "存款保险偿付限额是多少", "股票注册制改革主要变化", "征信查询收费不",
        "理财产品风险分级", "基金赎回到账时间", "大额存单提前支取规则",
        "融资融券平仓线", "ETC扣费失败怎么办", "信用卡逾期后果",
        "外汇现钞现汇区别",
    ]
    add([f"知识库里有没有关于{q}的材料" for q in rag_faq] + [f"请检索{q}相关的政策条款" for q in rag_faq], "rag", tags=("kb",))

    # 政策解读/文档问答类扩充
    rag_interp = [
        "通俗解释一下什么是存款保险",
        "股票注册制是什么意思",
        "简述基金定投的优缺点",
        "金融消费者八项权益有哪些",
        "信用卡停息挂账如何申请",
        "手机银行转账限额是多少",
        "商业保险与社保的区别",
        "什么是绿色债券",
        "银行破产怎么处理我的存款",
        "可转债和普通债券的区别",
        "账单分期手续费怎么算",
        "什么是净息差",
        "城投债有什么特征",
        "REITs是什么",
        "固定资产折旧方法有哪些",
        "什么是资本充足率",
    ]
    add(rag_interp, "rag", tags=("interp",))
    add([f"根据{qi}，梳理要点" for qi in rag_interp[:8]] + [f"总结一下{qi}的核心内容" for qi in rag_interp[:8]], "rag", tags=("summary",))

    add(CHITCHAT, "chitchat", tags=("curated",))
    add(["请问你能提供哪些帮助?", "现在方便聊会天吗?", "周末愉快", "认识你很高兴"], "chitchat", tags=("more",))
    add(MULTIMODAL, "multimodal", tags=("curated",))
    # 多模态变体
    add([f"把这张{q}识别出来" for q in ["发票", "化验单", "证件照", "扫描合同"]], "multimodal", tags=("parse",))
    add([f"解析一下这份征求件的扫描版本", "提取截图里的商品价格", "读取这张表格的照片内容"], "multimodal", tags=("more",))

    # 去重保序
    seen, out = set(), []
    for it in items:
        if it["question"] not in seen:
            seen.add(it["question"])
            out.append(it)
    return out


def main() -> None:
    import json
    from pathlib import Path

    data = build()
    out = Path(__file__).resolve().parent / "route_skill_eval.json"
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    from collections import Counter

    print(f"生成 {len(data)} 题 -> {out}")
    print(Counter(it["skill"] for it in data))


if __name__ == "__main__":
    main()